  App.form('feedback', async function (form, d) {
    var body = { topic: d.topic, message: d.message, name: d.name, email: d.email, page: App.here(), website: d.website };
    App.forms.check(form, 'feedback', body);
    await App.api.post('feedback', body);
    form.outerHTML = String(h`<div class="notice notice-ok" role="status" tabindex="-1" id="fb-ok">${App.icon('check', 'notice-i')}<div><p class="notice-title">Спасибо! Сообщение отправлено</p><p>${d.email ? 'Мы ответим на указанную почту.' : 'Мы учтём его в работе.'}</p></div></div>`);
    App.focus('fb-ok');
  });

